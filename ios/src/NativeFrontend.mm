static UITextView *g_log_text = nil;

static void update_log_overlay(UIWindow *window) {
    const BOOL show_log = [NSUserDefaults.standardUserDefaults boolForKey:@"vita3k.perf.log"];
    if (!show_log || !window) {
        g_log_hud.hidden = YES;
        return;
    }
    if (!g_log_hud) {
