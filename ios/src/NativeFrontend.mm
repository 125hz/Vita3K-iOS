// Game-controller navigation for the native UI.
//
// This used to walk g_library's UIView subtree, collect focusable views, and
// move a focus ring spatially. The library is SwiftUI now and has no such
// subtree, so the navigator is reduced to what it should always have been: it
// reads the controller and forwards intent. LibraryState owns which game is
// focused and maps D-pad movement onto whichever presentation is showing (see
// LibraryState.FocusLayout); the view draws the ring and scrolls it into view.
//
// Handlers no-op whenever the library is off screen, so in-game input is never
// intercepted.
@interface Vita3KPadNavigator : NSObject
@property(nonatomic) BOOL active;
+ (instancetype)shared;
- (void)start;
- (void)stop;
@end

@implementation Vita3KPadNavigator

+ (instancetype)shared {
    static Vita3KPadNavigator *navigator;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        navigator = [[Vita3KPadNavigator alloc] init];
        [NSNotificationCenter.defaultCenter addObserverForName:GCControllerDidConnectNotification
                                                        object:nil
                                                         queue:NSOperationQueue.mainQueue
                                                    usingBlock:^(NSNotification *note) {
            [navigator wireController:note.object];
        }];
    });
    return navigator;
}

- (void)start {
    self.active = YES;
    for (GCController *controller in GCController.controllers)
        [self wireController:controller];
}

- (void)stop {
    self.active = NO;
    [TsubomiLibraryStateBridge clearFocus];
}

- (void)wireController:(GCController *)controller {
    GCExtendedGamepad *pad = controller.extendedGamepad;
    if (!pad)
        return;
    __weak Vita3KPadNavigator *weakSelf = self;
    pad.dpad.up.pressedChangedHandler = ^(__unused GCControllerButtonInput *b, __unused float v, BOOL pressed) {
        if (pressed) [weakSelf moveX:0 y:-1];
    };
    pad.dpad.down.pressedChangedHandler = ^(__unused GCControllerButtonInput *b, __unused float v, BOOL pressed) {
        if (pressed) [weakSelf moveX:0 y:1];
    };
    pad.dpad.left.pressedChangedHandler = ^(__unused GCControllerButtonInput *b, __unused float v, BOOL pressed) {
        if (pressed) [weakSelf moveX:-1 y:0];
    };
    pad.dpad.right.pressedChangedHandler = ^(__unused GCControllerButtonInput *b, __unused float v, BOOL pressed) {
        if (pressed) [weakSelf moveX:1 y:0];
    };
    pad.buttonA.pressedChangedHandler = ^(__unused GCControllerButtonInput *b, __unused float v, BOOL pressed) {
        if (pressed) [weakSelf activate];
    };
    pad.buttonB.pressedChangedHandler = ^(__unused GCControllerButtonInput *b, __unused float v, BOOL pressed) {
        if (pressed) [weakSelf back];
    };
    pad.buttonY.pressedChangedHandler = ^(__unused GCControllerButtonInput *b, __unused float v, BOOL pressed) {
        if (pressed) [weakSelf gameActions];
    };
    // L1/R1 cycled the old settings screen's categories. The SwiftUI settings
    // screen is one scrolling Form, so there is nothing to cycle; the handlers
    // are cleared rather than left pointing at a removed method.
    pad.leftShoulder.pressedChangedHandler = nil;
    pad.rightShoulder.pressedChangedHandler = nil;
}

// The library is driveable only while it is on screen and nothing is presented
// over it. A presented sheet (settings, trophies) is SwiftUI's to handle.
// Whatever the library currently has presented over it - a settings/trophy
// sheet, or the pad-actions / delete confirmation dialog. The library is
// parented to the window with no containment (see vita3k_ios_show_library), so
// SwiftUI presents from g_library_controller, not from window.rootViewController
// - checking only the latter let controller input keep driving the library
// behind an open context menu, so Cross booted a game instead of picking an
// item.
static UIViewController *library_presented_controller() {
    if (g_library_controller.presentedViewController)
        return g_library_controller.presentedViewController;
    return library_view().window.rootViewController.presentedViewController;
}

- (BOOL)navigationAllowed {
    return self.active
        && library_view().window != nil
        && library_presented_controller() == nil;
}

- (void)moveX:(NSInteger)dx y:(NSInteger)dy {
    if (![self navigationAllowed])
        return;
    [TsubomiLibraryStateBridge moveFocusByX:dx y:dy];
}

- (void)activate {
    if (![self navigationAllowed])
        return;
    [TsubomiLibraryStateBridge activateFocused];
}

- (void)gameActions {
    if (![self navigationAllowed])
        return;
    [TsubomiLibraryStateBridge showActionsForFocused];
}

- (void)back {
    if (!self.active)
        return;
    // Circle dismisses whatever the library has presented - including the
    // pad-actions dialog opened with Triangle - which is why this looks at the
    // library controller too, not only the window root.
    UIViewController *presented = library_presented_controller();
    if (presented) {
        [presented dismissViewControllerAnimated:YES completion:nil];
        return;
    }
    // Nothing presented: drop the focus ring so the library returns to its
    // touch-driven appearance.
    [TsubomiLibraryStateBridge clearFocus];
}

@end

// Presents the Files picker and hands the copied file to the emulator loop.
@interface Vita3KImportPicker : NSObject <UIDocumentPickerDelegate>
@property(nonatomic) Vita3KIOSFrontendActionKind kind;
@property(nonatomic, copy) NSString *titleId;
@end

@implementation Vita3KImportPicker

- (void)documentPicker:(UIDocumentPickerViewController *)controller didPickDocumentsAtURLs:(NSArray<NSURL *> *)urls {
    (void)controller;
    NSURL *url = urls.firstObject;
    if (!url)
        return;
    const BOOL scoped = [url startAccessingSecurityScopedResource];
    NSString *documents = NSSearchPathForDirectoriesInDomains(NSDocumentDirectory, NSUserDomainMask, YES).firstObject;
    NSString *importDir = [[documents stringByAppendingPathComponent:@"Tsubomi"] stringByAppendingPathComponent:@"import"];
    [NSFileManager.defaultManager createDirectoryAtPath:importDir withIntermediateDirectories:YES attributes:nil error:nil];
    NSString *destination = [importDir stringByAppendingPathComponent:url.lastPathComponent];
    [NSFileManager.defaultManager removeItemAtPath:destination error:nil];
    NSError *error = nil;
    const BOOL copied = [NSFileManager.defaultManager copyItemAtURL:url
                                                              toURL:[NSURL fileURLWithPath:destination]
                                                              error:&error];
    if (scoped)
        [url stopAccessingSecurityScopedResource];
    if (!copied) {
        // A common cause is an iCloud-only file whose contents were never
        // downloaded, or insufficient free space for the working copy. Surface
        // the underlying reason instead of a bare "could not copy".
        const char *reason = error.localizedDescription.UTF8String ?: "unknown error";
        LOG_ERROR("iOS import copy failed for '{}': {}",
            url.lastPathComponent.UTF8String ?: "?", reason);
        vita3k_ios_report_import_result(
            std::string("Could not read the selected file: ") + reason
                + ". If it is stored in iCloud, download it in Files first.",
            false);
        return;
    }
    NSString *busy = @"Installing game…";
    if (self.kind == Vita3KIOSFrontendActionKind::ImportFirmware)
        busy = @"Installing firmware…";
    else if (self.kind == Vita3KIOSFrontendActionKind::ImportLicense)
        busy = @"Installing license…";
    else if (self.kind == Vita3KIOSFrontendActionKind::ImportSave)
        busy = @"Importing save…";
    [TsubomiLibraryStateBridge setBusyMessage:busy];
    Vita3KIOSFrontendAction action;
    action.kind = self.kind;
    action.app_path = destination.UTF8String;
    action.title_id = self.titleId.UTF8String ?: "";
    queue_action(std::move(action));
}

@end

